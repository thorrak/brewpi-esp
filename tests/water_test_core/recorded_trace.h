inline void firstPulseRegression() {
  using namespace WaterTestCore;
  Program p;
  assert(p.start(0, 20, 2, 2));
  p.noiseC = baselineNoiseC;
  p.baselineDrift = baselineDrift;
  for (const auto &reading : beer) {
    const double now = reading.recordedUs / 1e6;
    if (!p.pulse && reading.recordedUs >= firstPulseOnUs) {
      // Use the saved boundary: the export does not contain every baseline read.
      p.role = Role::Calibration;
      p.beginPulse(firstPulseOnUs / 1e6);
      assert(p.beforePulseC == 20.0625);
    }
    if (p.pump && reading.recordedUs >= firstPulseOffUs)
      p.observe(firstPulseOffUs / 1e6);
    p.sample(reading.readUs / 1e6, reading.sixteenthsC / 16., true, now);
    if (p.pulse)
      p.tick(now);
    assert(p.peakResponse <= .1875);
    assert(!p.usefulResponse && !p.contrastStarted);
    if (p.pulse == 2) {
      assert(p.pump && p.role == Role::Calibration);
      assert(p.deadline - p.pulseStarted == 30.);
      return;
    }
  }
  assert(p.peakResponse == .1875 && p.completedPulses == 1 && !p.pump);
  // Sparse exported readings cannot establish the full acquisition's settling
  // statistics. An observation timeout must stay inconclusive rather than
  // treating that missing evidence as a useful response.
  const double nextDecision = beer[sizeof(beer) / sizeof(beer[0]) - 1].recordedUs / 1e6 + 1.;
  p.deadline = nextDecision;
  p.tick(nextDecision);
  assert(!p.active() && !p.pump && p.outcome == End::Inconclusive);
  assert(p.pulse == 1 && !p.usefulResponse && !p.contrastStarted);
}
